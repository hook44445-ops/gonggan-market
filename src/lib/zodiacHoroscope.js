// 공간라운지 오늘의 별자리 운세 — 12별자리 (10-01 대표 «인도점성술은 빼고 별자리 정도는 넣고»)
//
//   인도점성술(월별 운세) 자리를 대신한다. 콘텐츠 종류 id 는 예전 그대로 "astrology"
//   (편성 시각 · 품질 검토 «오락·참고 고지 · 단정 금지» · 사진 분류를 그대로 쓴다).
//   관리자 화면(자동 편성 · 실험: 라이브 운영)에서 사람이 눌러 만든다 — 서버가 트렌드로 자동 발행하지 않는다.
//   개인 생년월일/차트 없음 · 쉽고 짧게 · 겁주는 표현/단정 금지 · 끝에 «오락·참고용» 한 줄.
//   순수 함수 · DB/API 없음.
// ════════════════════════════════════════════════════════════════════

const WD = ["일", "월", "화", "수", "목", "금", "토"];
const fmt = (d) => `${d.getFullYear()}년 ${d.getMonth() + 1}월 ${d.getDate()}일(${WD[d.getDay()]})`;

// 별자리 · 날짜(양력) — 흔히 쓰는 구분
export const ZODIAC_SIGNS = [
  ["양자리", "3/21~4/19"], ["황소자리", "4/20~5/20"], ["쌍둥이자리", "5/21~6/21"], ["게자리", "6/22~7/22"],
  ["사자자리", "7/23~8/22"], ["처녀자리", "8/23~9/22"], ["천칭자리", "9/23~10/22"], ["전갈자리", "10/23~11/21"],
  ["사수자리", "11/22~12/21"], ["염소자리", "12/22~1/19"], ["물병자리", "1/20~2/18"], ["물고기자리", "2/19~3/20"],
];

export const ZODIAC_DISCLAIMER = "(본 콘텐츠는 오락·참고용입니다.)";

export function zodiacTitle(now = Date.now()) {
  return `⭐ ${fmt(new Date(now))} 오늘의 별자리 운세`;
}

export function zodiacPrompt(now = Date.now()) {
  const d = new Date(now);
  return [
    `"${d.getFullYear()}년 ${d.getMonth() + 1}월 ${d.getDate()}일 오늘의 별자리 운세"를 작성한다.`,
    `개인 생년월일/차트를 쓰지 않고 12별자리별로만 쓴다.`,
    `형식:`,
    `- ${ZODIAC_SIGNS.map(([n, r]) => `${n}(${r})`).join(", ")} 순서로 각 2~3문장.`,
    `- 각 항목: 오늘의 흐름 + 관계/일/돈 중 하나의 팁 + «오늘의 집 한 가지»(창문 열기·책상 정리·조명 바꾸기처럼 집에서 바로 할 수 있는 작은 일 1개).`,
    `원칙: 쉽고 짧게 · 밝고 재미있게 · 공유하기 좋게. 겁주는 표현 · 단정적 예언 · 건강/투자 조언 금지.`,
    `맨 끝에 한 줄: ${ZODIAC_DISCLAIMER}`,
  ].join("\n");
}

export function zodiacMeta(now = Date.now()) {
  return {
    contentType: "astrology",
    title: zodiacTitle(now),
    signs: ZODIAC_SIGNS.map(([n]) => n),
    shareCopy: "⭐ 오늘의 별자리 운세 — 내 별자리는? 오늘 집에서 할 한 가지도 확인해 보세요.",
    seoFirst: true,
  };
}
