/** 문자열 → 안정적인 정수(같은 입력은 늘 같은 값). */
export function hashOf(str) {
  let h = 2166136261;
  const s = String(str ?? "");
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }
  return Math.abs(h);
}

