/** 오늘의 카테고리 주제 count 개 — 카테고리를 차례대로, 같은 주제는 한 바퀴 뒤에(variant+1). */
export function pickCategoryTopics(count = 3, day = 0) {
  const out = [];
  for (let i = 0; i < count; i++) {
    const n = day * count + i;                                   // 칸 번호 — 계속 커진다
    const cat = CATEGORY_ROTATION[n % CATEGORY_ROTATION.length];
    const lap = Math.floor(n / CATEGORY_ROTATION.length);        // 이 카테고리가 몇 번째 차례인가
    const list = CATEGORY_TOPICS[cat];
    const t = list[lap % list.length];
    out.push({ ...t, category: cat, audience: "category", variant: Math.floor(lap / list.length), rotation: n });
  }
  return out;
}

/** 카테고리 글 한 편 — { title, content, category, tags }(generateDraft 와 같은 모양). */
export function composeCategoryPost(t, { day = 0 } = {}) {
  const v = Number(t.variant ?? 0) + day;
  const [h1, h2, h3] = HEADINGS[v % HEADINGS.length];
  // 다시 나올 때는 핵심 순서를 한 칸 민다 — 같은 주제라도 글의 모양이 달라진다
  const shift = Number(t.variant ?? 0) % t.points.length;
  const points = [...t.points.slice(shift), ...t.points.slice(0, shift)];
  const lines = [
    `**한 줄 요약**: ${t.points[0]}.`,
    "",
    INTROS[v % INTROS.length](t.topic),
    "",
    `## ${h1}`,
    ...points.map((p) => `- ${p}`),
    "",
    `## ${h2}`,
    t.todo,
    "",
    `## ${h3}`,
    t.ask,
    "댓글로 남겨 주시면 다음 글에서 함께 모아 보겠습니다.",
  ];
  if (CARE_NOTE[t.category]) lines.push("", `> ${CARE_NOTE[t.category]}`);
  return {
    title: t.angle,
    content: lines.join("\n"),
    category: t.category,
    tags: [t.topic, t.category].filter(Boolean),
  };
}
