export const segText = (segs) => (Array.isArray(segs) ? segs : [segs]).map((x) => (typeof x === "string" ? x.replace(/\n/g, " ") : x?.b ?? "")).join("");
const escHtml = (s) => String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
export const segHtml = (segs) => (Array.isArray(segs) ? segs : [segs])
  .map((x) => (typeof x === "string" ? escHtml(x).replace(/\n/g, "<br>") : `<strong>${escHtml(x?.b)}</strong>`)).join("");
